"""Eval 報告渲染：合併各 suite 最新結果 → ``docs/eval_report.md``。

合併語意：本次執行的結果優先；本次沒跑（或被跳過）的 suite 退回
``eval/.cache/results/`` 的上一份存檔——多天分批跑（judge 額度限制）最終
收斂成一份完整報告。跳過與部分完成都如實標注（measure-and-report 精神）。
"""

import subprocess
from datetime import UTC, datetime
from pathlib import Path

import eval._bootstrap  # noqa: F401  # isort: split
from eval.config import ALL_SUITES, REPO_ROOT, EvalConfig
from eval.suites import SuiteResult, load_result

# 報告章節順序與標題（kit_generation 是 rubric 的內部前置，放附錄）。
_SECTIONS: list[tuple[str, str]] = [
    ("matching", "1. Job matching — Precision@K / MRR vs TF-IDF baseline"),
    ("rag", "2. RAG retrieval — Precision@K / MRR, rerank ablation"),
    ("hallucination", "3. Hallucination detection — LLM-as-judge (RAG vs no-RAG)"),
    ("rubric", "4. Resume-suggestion quality — rubric scores"),
    ("reliability", "5. Reliability — malformed-response & fallback rates"),
    ("system", "6. System metrics — latency, error rate, coverage"),
    ("kit_generation", "Appendix A. Rubric input generation"),
]

_SELF_GRADING_CAVEAT = (
    "> **Judge caveat (self-grading):** the judge model (`gemini-3.6-flash`) belongs to "
    "the same model family as — and is the production fallback for — the generator "
    "(`gemini-3.5-flash-lite`). Same-family judges can be systematically blind to their "
    "family's characteristic errors, so absolute rates may be optimistic; the RAG vs "
    "no-RAG *comparison* (same judge on both sides) is the more trustworthy signal."
)


def _git_sha() -> str:
    try:
        out = subprocess.run(
            ["git", "rev-parse", "--short", "HEAD"],
            cwd=REPO_ROOT,
            capture_output=True,
            text=True,
            timeout=10,
        )
        return out.stdout.strip() or "unknown"
    except Exception:
        return "unknown"


def _render_table(table: dict) -> list[str]:
    headers = [str(h) for h in table["headers"]]
    lines = [f"**{table['title']}**", ""]
    lines.append("| " + " | ".join(headers) + " |")
    lines.append("|" + "|".join(["---"] * len(headers)) + "|")
    for row in table["rows"]:
        lines.append("| " + " | ".join(str(cell) for cell in row) + " |")
    lines.append("")
    return lines


def _render_suite(name: str, title: str, result: SuiteResult | None) -> list[str]:
    lines = [f"## {title}", ""]
    if result is None:
        lines += ["_Not yet run — execute `python eval/run_eval.py` (see notes on flags)._", ""]
        return lines
    if result.skipped:
        reasons = "; ".join(result.notes) or "skipped"
        lines += [f"_Skipped this report: {reasons}_", ""]
        return lines
    if result.partial:
        lines += ["_Partial results — see notes below for what is missing and why._", ""]
    if name in ("hallucination", "rubric"):
        lines += [_SELF_GRADING_CAVEAT, ""]
    for table in result.tables:
        lines += _render_table(table)
    if result.notes:
        lines.append("Notes:")
        lines += [f"- {note}" for note in result.notes]
        lines.append("")
    if result.generated_at:
        lines += [f"_Collected: {result.generated_at}_", ""]
    return lines


def render_report(
    run_results: dict[str, SuiteResult],
    cfg: EvalConfig,
    *,
    scenario_count: int,
    offline: bool,
) -> Path:
    """合併結果並寫出 Markdown 報告；回傳輸出路徑。"""
    lines: list[str] = [
        "# CareerPilot AI — Evaluation Report",
        "",
        "_Generated by `python eval/run_eval.py` (Phase 8). Do not edit by hand._",
        "",
        "| Run info | |",
        "|---|---|",
        f"| Generated at | {datetime.now(UTC).isoformat(timespec='seconds')} |",
        f"| Git commit | {_git_sha()} |",
        f"| Scenarios in dataset | {scenario_count} |",
        f"| Scenario limit this run | {cfg.limit or 'none'} |",
        f"| LLM cache | {'disabled (--no-cache)' if cfg.no_cache else 'enabled'} |",
        f"| Mode | {'offline (no GEMINI_API_KEY: cache-only)' if offline else 'online'} |",
        f"| Judge model | {cfg.judge_model} |",
        "",
        "Suites can be (re-)run independently and on different days (free-tier quota); "
        "each section below shows the latest collected result for that suite.",
        "",
    ]

    for name, title in _SECTIONS:
        result = run_results.get(name)
        if result is None or result.skipped:
            # 本次沒跑 / 被跳過：退回上一份存檔（若有），但跳過的原因
            # 不能被吃掉——附註在存檔結果上，讀者才知道本次沒有更新。
            saved = load_result(cfg, name)
            if saved is not None:
                if result is not None and result.skipped:
                    reason = "; ".join(result.notes) or "skipped"
                    saved.notes.append(
                        f"This run skipped the suite ({reason}); "
                        "the numbers above are the last collected result."
                    )
                result = saved
        lines += _render_suite(name, title, result)

    cfg.report_path.parent.mkdir(parents=True, exist_ok=True)
    cfg.report_path.write_text("\n".join(lines), encoding="utf-8")
    return cfg.report_path


def suites_in_report() -> tuple[str, ...]:
    return tuple(name for name, _ in _SECTIONS if name in ALL_SUITES)
